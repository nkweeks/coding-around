// Deploy the self-contained v3 runtime, never the source repository or legacy games.
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = process.env.VIM_PROTOCOL_SOURCE || '/Users/nathanielweeks/Documents/claude_code_projects/hacking_game'
const targetRoot = path.resolve(process.env.VIM_PROTOCOL_TARGET || path.join(repoRoot, 'public/vim-protocol'))
const entryFile = path.resolve(process.env.VIM_PROTOCOL_ENTRY || path.join(repoRoot, 'src/vimProtocolEntry.js'))
const manifest = JSON.parse(fs.readFileSync(path.join(sourceRoot, 'package.json'), 'utf8'))
if (manifest.name !== 'vim-protocol' || !/^3\.\d+\.\d+$/.test(manifest.version)) {
  throw new Error('Expected the VIM Protocol 3 source project')
}
// A tight include list prevents .git, tests, local settings, and old assets from being published.
fs.mkdirSync(targetRoot, { recursive: true })
fs.mkdirSync(path.dirname(entryFile), { recursive: true })
execFileSync('rsync', [
  '-a', '--delete', '--delete-excluded',
  '--include=/index.html', '--include=/v3/', '--include=/v3/***', '--exclude=*',
  `${sourceRoot}/`, `${targetRoot}/`,
], { stdio: 'inherit' })
const targetIndex = path.join(targetRoot, 'index.html')
let html = fs.readFileSync(targetIndex, 'utf8')
html = html.replace('<head>', '<head>\n  <base href="/vim-protocol/">')
html = html.replace('</body>', '  <a class="portfolio-return" href="/">Back to Coding Around</a>\n</body>')
fs.writeFileSync(targetIndex, html)
fs.writeFileSync(entryFile, `// Generated by sync:vim-protocol. The game owns its complete document.\nexport default '/vim-protocol/index.html?v=${manifest.version}'\n`)
console.log(`Synced VIM Protocol ${manifest.version} from ${sourceRoot}`)
